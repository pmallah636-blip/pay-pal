-- ====================================================================
-- PayMind Migration 005: Fix Preview RLS & Replace Token with Hash
-- ====================================================================
-- PURPOSE: Forward migration for databases that already have migration
--          002/003/004 applied. Removes the insecure public SELECT policy
--          and replaces raw session_token storage with SHA-256 hashes.
--
-- SAFETY:
--   - Idempotent: safe to run multiple times.
--   - No DROP TABLE, no TRUNCATE, no DELETE FROM.
--   - Existing sessions with session_token are migrated to token_hash.
--   - Existing sessions without session_token are set to a placeholder hash
--     (they will require new links to be generated by the seller).
--
-- IMPORTANT: After this migration, any preview link shared before this
--   migration was run will need to be re-shared IF the existing session_token
--   column is not present (i.e. the app was already storing hashes).
--   If session_token IS present, the migration populates token_hash from it.
-- ====================================================================

DO $$ BEGIN

  -- ----------------------------------------------------------------
  -- 1. Remove insecure "Public token access" policy if it exists
  -- ----------------------------------------------------------------
  DROP POLICY IF EXISTS "Public token access for authenticated preview" ON public.preview_sessions;
  RAISE NOTICE 'Migration 005: Dropped insecure public SELECT policy if it existed.';

  -- ----------------------------------------------------------------
  -- 2. Add token_hash column if not already present
  -- ----------------------------------------------------------------
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'preview_sessions'
      AND column_name = 'token_hash'
  ) THEN
    ALTER TABLE public.preview_sessions ADD COLUMN token_hash TEXT;
    RAISE NOTICE 'Migration 005: Added token_hash column.';

    -- Populate from existing session_token if present
    IF EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'public'
        AND table_name = 'preview_sessions'
        AND column_name = 'session_token'
    ) THEN
      UPDATE public.preview_sessions
        SET token_hash = encode(sha256(session_token::bytea), 'hex')
        WHERE session_token IS NOT NULL;
      -- Rows without session_token get a placeholder; seller must regenerate link
      UPDATE public.preview_sessions
        SET token_hash = 'migration_placeholder_' || encode(sha256(id::bytea), 'hex')
        WHERE session_token IS NULL AND token_hash IS NULL;
      RAISE NOTICE 'Migration 005: Populated token_hash from existing session_token values.';
    ELSE
      -- No session_token column; set placeholder for all rows
      UPDATE public.preview_sessions
        SET token_hash = 'migration_placeholder_' || encode(sha256(id::bytea), 'hex')
        WHERE token_hash IS NULL;
      RAISE NOTICE 'Migration 005: session_token column not found; set placeholder token_hash values.';
    END IF;
  END IF;

  -- ----------------------------------------------------------------
  -- 3. Set token_hash NOT NULL (after population)
  -- ----------------------------------------------------------------
  BEGIN
    ALTER TABLE public.preview_sessions ALTER COLUMN token_hash SET NOT NULL;
    RAISE NOTICE 'Migration 005: Set token_hash NOT NULL.';
  EXCEPTION WHEN others THEN
    RAISE NOTICE 'Migration 005: Could not set token_hash NOT NULL (may already be set or nulls remain): %', SQLERRM;
  END;

  -- ----------------------------------------------------------------
  -- 4. Add UNIQUE constraint on token_hash if not present
  -- ----------------------------------------------------------------
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints tc
    JOIN information_schema.constraint_column_usage ccu
      ON tc.constraint_name = ccu.constraint_name
      AND tc.constraint_schema = ccu.constraint_schema
    WHERE tc.table_schema = 'public'
      AND tc.table_name = 'preview_sessions'
      AND tc.constraint_type = 'UNIQUE'
      AND ccu.column_name = 'token_hash'
  ) THEN
    ALTER TABLE public.preview_sessions
      ADD CONSTRAINT preview_sessions_token_hash_key UNIQUE (token_hash);
    RAISE NOTICE 'Migration 005: Added UNIQUE constraint on token_hash.';
  END IF;

  -- ----------------------------------------------------------------
  -- 5. Add index on token_hash if not present
  -- ----------------------------------------------------------------
  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE schemaname = 'public'
      AND tablename = 'preview_sessions'
      AND indexname = 'idx_preview_sessions_token_hash'
  ) THEN
    CREATE INDEX idx_preview_sessions_token_hash ON public.preview_sessions(token_hash);
    RAISE NOTICE 'Migration 005: Created index idx_preview_sessions_token_hash.';
  END IF;

  -- ----------------------------------------------------------------
  -- 6. Drop raw session_token column if still present
  --    (raw tokens must not persist in the database)
  -- ----------------------------------------------------------------
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'preview_sessions'
      AND column_name = 'session_token'
  ) THEN
    -- Drop unique constraint on session_token first if it exists
    ALTER TABLE public.preview_sessions
      DROP CONSTRAINT IF EXISTS preview_sessions_session_token_key;
    -- Drop the index on session_token if it exists
    DROP INDEX IF EXISTS public.idx_preview_sessions_token;
    -- Drop the column
    ALTER TABLE public.preview_sessions DROP COLUMN session_token;
    RAISE NOTICE 'Migration 005: Dropped raw session_token column.';
  END IF;

  -- ----------------------------------------------------------------
  -- 7. Ensure RLS is enabled
  -- ----------------------------------------------------------------
  ALTER TABLE public.preview_sessions ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.preview_audit_logs ENABLE ROW LEVEL SECURITY;

  -- ----------------------------------------------------------------
  -- 8. Ensure seller management policy exists (recreate if dropped)
  -- ----------------------------------------------------------------
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'preview_sessions'
      AND policyname = 'Sellers can manage own preview sessions'
  ) THEN
    CREATE POLICY "Sellers can manage own preview sessions"
      ON public.preview_sessions FOR ALL USING (auth.uid() = seller_id);
    RAISE NOTICE 'Migration 005: Created policy "Sellers can manage own preview sessions".';
  END IF;

  -- ----------------------------------------------------------------
  -- 9. Ensure audit logs seller policy exists
  -- ----------------------------------------------------------------
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'preview_audit_logs'
      AND policyname = 'Sellers can view audit logs for own sessions'
  ) THEN
    CREATE POLICY "Sellers can view audit logs for own sessions"
      ON public.preview_audit_logs FOR SELECT
      USING (
        EXISTS (
          SELECT 1 FROM public.preview_sessions ps
          WHERE ps.id = preview_audit_logs.session_id
            AND ps.seller_id = auth.uid()
        )
      );
    RAISE NOTICE 'Migration 005: Created policy "Sellers can view audit logs for own sessions".';
  END IF;

  RAISE NOTICE 'Migration 005 completed successfully.';

END $$;
